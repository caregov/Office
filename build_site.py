def slugify_keywords(service):
    """يولّد كلمات مفتاحية بسيطة من عنوان الخدمة لعرضها أسفل المقال (تقليد لنمط abu-ayman.com)."""
    base = service["title"]
    extra = ["السعودية","2027", "أبو محمد", base.replace("خدمات ", "").replace("تصاريح ", "").strip()]
    return list(dict.fromkeys([base] + extra))

def related_html(service, base=""):
    """يبني كتلة 'خدمات ذات صلة' بروابط لصفحات أخرى مرتبطة."""
    cards = []
    for rid in service["related"]:
        r = SERVICE_BY_ID.get(rid)
        if not r:
            continue
        cards.append(f'''
        <a href="{base}{r['id']}.html" class="related-card">
          <span class="related-cat">{CATEGORIES[r['cat']]}</span>
          <h4>{r['title']}</h4>
          <p>{r['short']}</p>
          <span class="related-more">اقرأ المزيد ←</span>
        </a>''')
    return "\n".join(cards)

def faq_html(service):
    items = []
    for i, (q, a) in enumerate(service["faqs"]):
        open_cls = " open" if i == 0 else ""
        items.append(f'''
        <div class="faq-item{open_cls}">
          <div class="faq-q"><span>{q}</span><span class="plus">+</span></div>
          <div class="faq-a">{a}</div>
        </div>''')
    return "\n".join(items)

def list_html(items, ordered=False):
    tag = "ol" if ordered else "ul"
    lis = "\n".join(f"          <li>{it}</li>" for it in items)
    return f"        <{tag} class=\"article-list\">\n{lis}\n        </{tag}>"

def keywords_html(service):
    kws = slugify_keywords(service)
    return "\n".join(f'<a href="{service["id"]}.html" class="kw-tag">{k}</a>' for k in kws)

def nav_dropdown(base=""):
    parts = []
    for cat_id, cat_name in CATEGORIES.items():
        items = [s for s in SERVICES if s["cat"] == cat_id]
        links = "\n".join(f'<a href="{base}pages/{s["id"]}.html">{s["title"]}</a>' for s in items)
        parts.append(f'''
        <div class="has-dropdown">
          <a href="{base}index.html#{cat_id}">{cat_name} ▾</a>
          <div class="dropdown">
            {links}
          </div>
        </div>''')
    return "\n".join(parts)

